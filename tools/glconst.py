import sys, json, re, collections

# glconst.py <index> <header> [GL_NAME ...]: regenerate `constexpr GLenum GL_X = v;` from LWJGL constant fields.
idx, hdr, *new = sys.argv[1:]
lw = json.load(open(f"{idx}/lwjgl.json"))
vals = collections.defaultdict(set)
for c, e in lw.items():
    if c.startswith("org/lwjgl/opengl/"):
        for n, d, a, cv in e["f"]:
            if isinstance(cv, int) and not isinstance(cv, bool) and n.startswith("GL_"):
                vals[n].add(cv)
try:
    old = re.findall(r"constexpr\s+\w+\s+(GL_\w+)\s*=", open(hdr).read())
except FileNotFoundError:
    old = []
names = sorted(set(old) | set(new))
bad = [n for n in names if len(vals.get(n, ())) != 1 or min(vals[n]) < 0]
if bad:
    sys.exit(f"[glconst] not resolvable from LWJGL: {bad}")
out = ["// Generated by tools/glconst.py from lwjgl-glfw-classes.jar; do not edit.", "#pragma once", ""]
out += [f"constexpr GLenum {n} = 0x{next(iter(vals[n])):X};" for n in names]
open(hdr, "w").write("\n".join(out) + "\n")
print(f"[glconst] {len(names)} constants ({len(set(names) - set(old))} new) -> {hdr}")
