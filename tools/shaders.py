import os, struct, subprocess, sys, tempfile

# shaders.py [root]: compile shaders/*.{vert,frag} to SPIR-V (Vulkan 1.1), check with spirv-val, write src/shaders.inc.
root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
out = ["// Generated by tools/shaders.py from shaders/; do not edit.", "#pragma once", "#include <cstdint>", ""]
for name, sym in (("ff.vert", "kFFVert"), ("ff.frag", "kFFFrag")):
    with tempfile.TemporaryDirectory() as td:
        spv = os.path.join(td, "o.spv")
        r = subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-o", spv,
                            os.path.join(root, "shaders", name)], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"[shaders] {name}: {r.stdout.strip()}")
        r = subprocess.run(["spirv-val", "--target-env", "vulkan1.1", spv], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"[shaders] spirv-val {name}: {r.stderr.strip()}")
        data = open(spv, "rb").read()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    out.append(f"inline constexpr uint32_t {sym}[] = {{")
    out += ["    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + "," for i in range(0, len(words), 8)]
    out += ["};", ""]
    print(f"[shaders] {name}: {len(words)} words, spirv-val ok")
open(os.path.join(root, "src", "shaders.inc"), "w").write("\n".join(out))
