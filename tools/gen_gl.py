import sys, os, re, json, collections

ROOT, IDX = sys.argv[1], sys.argv[2]
L = lambda f: json.load(open(os.path.join(IDX, f)))
lw, caps, reach = L("lwjgl.json"), L("glcaps_checks.json"), L("gl_reach.json")
GEN = {"src/gl/gl_enums.hpp": None, "src/gl/gl_decl.inc": None, "src/gl/procs.inc": None}
HDR = "// Generated by tools/gen_gl.py from third_party/lwjgl-glfw-classes.jar. Do not edit.\n"
mc_gl = set(reach["gl_functions"])

glconst = collections.defaultdict(set)
for c, e in lw.items():
    if c.startswith("org/lwjgl/opengl/"):
        for n, d, a, cv in e["f"]:
            if cv is not None and n.startswith("GL_") and d == "I":
                glconst[n].add(cv)

def strip(t):
    t = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group().count("\n"), t, flags=re.S)
    t = re.sub(r"//[^\n]*", "", t)
    return re.sub(r'"(?:\\.|[^"\\])*"', '""', t)

def close_paren(s, i):
    d = 0
    for j in range(i, len(s)):
        d += s[j] == "("; d -= s[j] == ")"
        if d == 0: return j
    return -1

files = []
for top in ("src", "tests"):
    for dp, dn, fn in os.walk(os.path.join(ROOT, top)):
        files += [os.path.join(dp, f) for f in fn if f.endswith((".cpp", ".hpp", ".h", ".inc"))]
files = sorted(f for f in files if os.path.relpath(f, ROOT) not in GEN)

defs, used, claim_v, claim_e = {}, set(), [], set()
for p in files:
    code = strip(open(p).read())
    claim_v += [(int(a), int(b)) for a, b in re.findall(r"\bORYON_CAP_VERSION\(\s*(\d)\s*,\s*(\d)\s*\)", code)]
    claim_e |= set(re.findall(r"\bORYON_CAP_EXT\(\s*(GL_\w+)\s*\)", code))
    code = re.sub(r"\bORYON_CAP_EXT\(\s*GL_\w+\s*\)", "", code)
    used |= set(re.findall(r"\bGL_[A-Z0-9_]+\b", code))
    for m in re.finditer(r"\bOGL_API\s+([\w\s\*]+?)\s*\b(gl[A-Z]\w*)\s*\(", code):
        e = close_paren(code, m.end() - 1)
        if e < 0 or not code[e + 1:].lstrip().startswith("{"): continue
        args = " ".join(code[m.end():e].split())
        ret = " ".join(m.group(1).split())
        if m.group(2) in defs: sys.exit(f"[gen_gl] duplicate OGL_API definition {m.group(2)}")
        defs[m.group(2)] = (ret, args or "void")

bad, enums = [], []
for n in sorted(used):
    v = glconst.get(n)
    if not v or len(v) != 1 or min(v) < 0: bad.append(n); continue
    enums.append((n, min(v)))

req = set()
for M, m in claim_v:
    for v in range(10, M * 10 + m + 1):
        req |= set(caps.get(f"GL{v}", []))
for f in claim_e:
    req |= set(caps.get(f[3:], []))
stubs = sorted(req - set(defs) - mc_gl)
missing = sorted((req & mc_gl) - set(defs))

def emit(rel, body):
    p = os.path.join(ROOT, rel); t = HDR + body
    if not os.path.exists(p) or open(p).read() != t:
        os.makedirs(os.path.dirname(p), exist_ok=True); open(p, "w").write(t)

emit("src/gl/gl_enums.hpp", '#pragma once\n#include "gl/gl_types.hpp"\n\n' +
     "".join(f"constexpr GLenum {n} = {v:#x};\n" for n, v in enums))
emit("src/gl/gl_decl.inc", "".join(f"OGL_API {r} {n}({a});\n" for n, (r, a) in sorted(defs.items())))
emit("src/gl/procs.inc", "".join(f"ORYON_STUB({n})\n" if n in stubs else f"ORYON_PROC({n})\n"
                                  for n in sorted(set(defs) | set(stubs))))
cv = ",".join(f"{M}.{m}" for M, m in claim_v) or "none"
print(f"[gen_gl] files={len(files)} enums={len(enums)} decls={len(defs)} procs={len(defs)} stubs={len(stubs)} "
      f"claim={cv}+{len(claim_e)}ext mc_coverage={len(mc_gl & set(defs))}/{len(mc_gl)} missing_for_claim={len(missing)}")
if bad:
    print(f"[gen_gl] unresolved GL_ names ({len(bad)}): {' '.join(bad[:20])}")
sys.exit(1 if bad else 0)
